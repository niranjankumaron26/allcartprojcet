CREATE DATABASE IF NOT EXISTS shopsphere_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE shopsphere_db;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 phone VARCHAR(20) NOT NULL, password_hash VARCHAR(255) NOT NULL, role ENUM('USER','ADMIN') NOT NULL DEFAULT 'USER',
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS categories (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE, description TEXT NOT NULL, image VARCHAR(500) NOT NULL
);
CREATE TABLE IF NOT EXISTS products (
 id INT AUTO_INCREMENT PRIMARY KEY, category_id INT NOT NULL, name VARCHAR(150) NOT NULL UNIQUE,
 description TEXT NOT NULL, price DECIMAL(12,2) NOT NULL CHECK(price>0), discount INT NOT NULL DEFAULT 0 CHECK(discount BETWEEN 0 AND 99),
 stock INT NOT NULL CHECK(stock>=0), image VARCHAR(500) NOT NULL, featured BOOLEAN NOT NULL DEFAULT FALSE,
 views INT NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT TRUE, FOREIGN KEY(category_id) REFERENCES categories(id)
);
CREATE TABLE IF NOT EXISTS cart (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL UNIQUE, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS cart_items (
 cart_id INT NOT NULL, product_id INT NOT NULL, quantity INT NOT NULL CHECK(quantity>0),
 PRIMARY KEY(cart_id,product_id), FOREIGN KEY(cart_id) REFERENCES cart(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS wishlist (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL UNIQUE, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS wishlist_items (
 wishlist_id INT NOT NULL, product_id INT NOT NULL, PRIMARY KEY(wishlist_id,product_id),
 FOREIGN KEY(wishlist_id) REFERENCES wishlist(id) ON DELETE CASCADE, FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS orders (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL,
 checkout_token VARCHAR(40) NOT NULL, UNIQUE(user_id,checkout_token),
 status ENUM('Pending','Confirmed','Processing','Shipped','Delivered','Cancelled') NOT NULL DEFAULT 'Pending',
 recipient VARCHAR(100) NOT NULL, phone VARCHAR(20) NOT NULL, address VARCHAR(500) NOT NULL,
 payment ENUM('COD','SIMULATED') NOT NULL, subtotal DECIMAL(14,2) NOT NULL, delivery DECIMAL(10,2) NOT NULL,
 total DECIMAL(14,2) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), INDEX(status,created_at)
);
CREATE TABLE IF NOT EXISTS order_items (
 id INT AUTO_INCREMENT PRIMARY KEY, order_id INT NOT NULL, product_id INT NOT NULL, product_name VARCHAR(150) NOT NULL,
 category_name VARCHAR(100) NOT NULL, quantity INT NOT NULL, unit_price DECIMAL(12,2) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id), FOREIGN KEY(product_id) REFERENCES products(id)
);
CREATE TABLE IF NOT EXISTS addresses (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, label VARCHAR(50) NOT NULL, address VARCHAR(500) NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS reviews (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, product_id INT NOT NULL,
 rating INT NOT NULL CHECK(rating BETWEEN 1 AND 5), body VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id,product_id),
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(product_id) REFERENCES products(id)
);
CREATE TABLE IF NOT EXISTS offers (
 id INT AUTO_INCREMENT PRIMARY KEY, product_id INT NOT NULL UNIQUE, title VARCHAR(100) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, FOREIGN KEY(product_id) REFERENCES products(id)
);
CREATE TABLE IF NOT EXISTS newsletter_subscribers (
 id INT AUTO_INCREMENT PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
